import type { ReactNode } from "react";

/**
 * The few icons the panel uses, drawn as inline SVG in the Feather style (outline, 2 px, round).
 * They only decorate: the words next to them say the same, so they are hidden from screen readers.
 */
function Icon({ children }: { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width="1em"
      height="1em"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

